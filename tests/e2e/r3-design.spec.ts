import { expect, test } from '@playwright/test'

test.use({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, reducedMotion: 'reduce' })

test('selection, reveal focus and record priority remain usable on mobile', async ({ page }) => {
  await page.goto('/')
  const nav = page.getByRole('navigation', { name: '移动端导航' })
  await nav.getByRole('button', { name: /牌卡百科/ }).click()
  await page.getByRole('button', { name: /查看全部 78 张/ }).click()
  const list = page.getByTestId('encyclopedia-list')
  expect(await list.evaluate(node => node.clientHeight)).toBeLessThanOrEqual(240)
  await list.getByRole('button', { name: /女祭司/ }).click()
  const detail = page.getByRole('article', { name: '女祭司 · 牌卡详情' })
  await expect(detail).toBeFocused()
  await expect.poll(async () => (await detail.boundingBox())!.y).toBeGreaterThanOrEqual(80)
  await expect.poll(async () => (await detail.boundingBox())!.y).toBeLessThan(140)

  await nav.getByRole('button', { name: /开始占卜/ }).click()
  await page.getByLabel('占卜问题', { exact: true }).fill('如何推进下一步？')
  await page.getByRole('button', { name: '事业', exact: true }).click()
  await page.getByRole('button', { name: '圣三角', exact: true }).click()
  await page.getByRole('button', { name: '洗牌并抽牌', exact: true }).click()
  const cards = page.locator('.spread-board__cards-layer').getByRole('button')
  await expect(cards).toHaveCount(3)
  const names = await cards.evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')))
  expect(new Set(names).size).toBe(3)
  await cards.first().focus()
  for (let index = 0; index < 3; index++) {
    await expect(cards.nth(index)).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(cards.nth(index)).toBeFocused()
    await expect(cards.nth(index)).toHaveAttribute('aria-disabled', 'true')
    if (index < 2) await page.keyboard.press('Tab')
  }
  await expect(page.getByRole('button', { name: '已全部揭晓', exact: true })).toHaveAttribute('aria-disabled', 'true')
  expect(await page.locator('.spread-board-shell').evaluate(node => Boolean(node.compareDocumentPosition(document.querySelector('[data-testid="deep-signals-panel"]')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true)
  await nav.getByRole('button', { name: /记录中心/ }).click()
  const records = page.locator('#records')
  await expect(records).toContainText('已存于此设备')
  await expect(records.getByRole('button', { name: '导出记录', exact: true })).toBeHidden()
  const first = records.locator('.record-card').first()
  await expect(first).toBeVisible()
  expect((await first.boundingBox())!.y).toBeLessThan(620)
  await records.getByText('更多筛选', { exact: true }).click()
  await expect(records.getByLabel('时间筛选')).toBeVisible()
  await records.getByText('导入与导出记录', { exact: true }).click()
  await expect(records.getByRole('button', { name: '导出记录', exact: true })).toBeVisible()
})
